export function getDealBySlug(categorySlug: string, dealSlug: string): Deal | undefined {
  return deals.find((d) => d.categorySlug === categorySlug && d.slug === dealSlug);
}

export function getDealsByCategory(categorySlug: string): Deal[] {
  return deals.filter((d) => d.categorySlug === categorySlug);
}

export function getDealsByDestination(destinationSlug: string): Deal[] {
  return deals.filter((d) => d.destinationSlug === destinationSlug);
}

export function getFeaturedDeals(): Deal[] {
  return deals.filter((d) => d.featured);
}

export function getRecentDeals(count: number): Deal[] {
  return deals.slice(0, count);
}
